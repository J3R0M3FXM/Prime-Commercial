import assert from 'node:assert/strict';
import { build } from 'rolldown';
const output=await build({input:'lib/pos-invoice-image.ts',write:false,platform:'node',output:{format:'esm'}});
const {drawPosInvoice,createPosInvoiceImage,POS_INVOICE_ARTWORK}=await import('data:text/javascript;base64,'+Buffer.from(output.output[0].code).toString('base64'));
const paint=[];
const ctx={measureText:value=>({width:value.length*15}),fillRect(...args){paint.push(['rect',...args]);},fillText(...args){paint.push(['text',...args,this.font]);},drawImage(...args){paint.push(['image',...args]);}};
const canvas={getContext:()=>ctx};
const qr={width:900,height:900};
const artwork={logo:{width:1740,height:342},background:{width:500,height:258}};
assert.equal(POS_INVOICE_ARTWORK.logo,'/prime-header-brand-refined.png');
assert.equal(POS_INVOICE_ARTWORK.background,'/prime-body-art.png');
const invoice={reference:'INV-123',customerName:'Customer',customerPhone:'09123456789',address:'Baguio City',createdAt:'2026-11-18T00:00:00Z',paymentStatus:'Unpaid',items:[{name:'Coffee',quantity:2,price:100,total:200}],subtotal:200,charges:[{name:'Packing',amount:5}],discounts:[{name:'Voucher',amount:10}],deliveryFee:40,total:235,payableNow:195,payableOnDelivery:40,payment:{id:'gcash',name:'GCash',accountName:'PRIME Store',accountNumber:'09111111111',qrCodeImage:'tgmedia:configured-qr'}};
drawPosInvoice(canvas,invoice,qr,artwork);
assert.ok(paint.some(op=>op[0]==='image'&&op[1]===artwork.logo));
assert.ok(paint.some(op=>op[0]==='image'&&op[1]===artwork.background));
const texts=paint.filter(op=>op[0]==='text').map(op=>op[1]);
for(const text of ['Order Invoice','Billed To','Order Summary','Payment Instructions','INV-123','Awaiting Payment','Coffee','PHP 100.00 Each','PHP 200.00','Packing','PHP 5.00','Voucher','PHP -10.00','PHP 235.00','Amount Due Now','PHP 195.00','Pay Courier On Delivery','PHP 40.00','GCash','PRIME Store','09111111111'])assert.ok(texts.includes(text),text);
assert.equal(paint.find(op=>op[0]==='image'&&op[1]===qr)[1],qr,'The configured QR artwork is used directly');
assert.ok(paint.filter(op=>op[0]==='text').every(op=>/Lato Condensed|Roboto Condensed/.test(op.at(-1))));
assert.ok(canvas.width+canvas.height<=10000);
paint.length=0;
drawPosInvoice(canvas,{...invoice,paymentStatus:'Paid'},undefined,artwork);
assert.ok(paint.some(op=>op[0]==='text'&&op[1]==='Paid'));
assert.equal(paint.some(op=>op[0]==='image'&&op[1]===qr),false);
assert.throws(()=>drawPosInvoice(canvas,{...invoice,items:[]},undefined,artwork),/between 1 and 100/);
globalThis.document={fonts:{ready:Promise.resolve()}};
await assert.rejects(createPosInvoiceImage(invoice),/configured payment QR could not be loaded/);
const loaded=[];
globalThis.Image=class{width=500;height=258;set src(value){loaded.push(value);if(value.includes('brand')){this.width=1740;this.height=342;}queueMicrotask(()=>this.onload());}};
globalThis.document.createElement=()=>({...canvas,toBlob:callback=>callback(new Blob(['png'],{type:'image/png'}))});
assert.equal((await createPosInvoiceImage(invoice,'data:image/png;base64,configured')).type,'image/png');
assert.deepEqual(loaded.sort(),[POS_INVOICE_ARTWORK.logo,POS_INVOICE_ARTWORK.background,'data:image/png;base64,configured'].sort());
globalThis.Image=class{set src(value){queueMicrotask(()=>this.onerror());}};
await assert.rejects(createPosInvoiceImage({...invoice,payment:{id:'',name:'Cash'}}),/official PRIME logo could not be loaded/);
console.log('PASS: invoice totals, delivery payment split, configured QR, required fonts and missing-QR failure.');
